let lastIndex = -1;

// 随机取一句，避免与上一次重复
export function randomQuote(): string {
  const count = focusQuotes.length;
  let index = Math.floor(Math.random() * count);
  if (count > 1 && index === lastIndex) {
    index = (index + 1) % count;
  }
  lastIndex = index;
  return focusQuotes[index];
}
